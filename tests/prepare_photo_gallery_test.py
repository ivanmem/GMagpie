"""Extract the photo-gallery decision logic (playlist, paging, stages, overlay).

Every function here is pure: it takes paths, sizes or key codes and returns
numbers or a list. Extracting the production text keeps the tests honest about
the code that ships while running without a window, a device or the app process.
"""
from pathlib import Path
import sys

repo = Path(__file__).resolve().parents[1]
out = Path(sys.argv[1])
out.mkdir(parents=True, exist_ok=True)


def extract(source_path, start_anchor, end_anchor):
    """The whole first definition after start_anchor, up to its closing brace."""
    source = source_path.read_text(encoding="utf-8-sig")
    start = source.index(start_anchor)
    end = source.index(end_anchor, start)
    code = source[start:end]
    # the slice ends with the doc comment of the following function - keep the
    # code up to and including its own closing brace (and its trailing ';')
    cut = code.rindex("}")
    if code[cut + 1:cut + 2] == ";":
        cut += 1
    return code[:cut + 1] + "\n"


renderer = repo / "src/GMagpie.Core/Renderer.cpp"
gallery = repo / "src/GMagpie/GalleryService.cpp"
gallery_h = repo / "src/GMagpie/GalleryService.h"
app = repo / "src/GMagpie/App.cpp"

parts = [
    ("Renderer.cpp: how many effect stages a photo needs",
     extract(renderer, "size_t CalcPhotoEffectStages(",
             "ID3D11Texture2D* Renderer::_ResizePhotoEffects(")),
    ("Renderer.cpp: where the photo frame is letterboxed into (scaled copy)",
     extract(renderer, "RECT CalcPhotoSceneViewport(",
             "void Renderer::_CopySceneToTarget(")),
    ("GalleryService.cpp: the supported image extensions",
     extract(gallery, "static const std::unordered_set<std::wstring> SUPPORTED_EXTENSIONS",
             "// Цикл апскейлеров для Num6")),
    ("GalleryService.cpp: album scan (recursion, extension filter, order)",
     extract(gallery, "static std::vector<std::wstring> BuildPhotoPlaylist(",
             "// Контекстное меню и")),
    ("GalleryService.cpp: restoring a page from a changed album",
     extract(gallery, "static size_t PhotoResumeIndex(",
             "bool GalleryService::Start(")),
    ("GalleryService.cpp: which page to prefetch next",
     extract(gallery, "static size_t PhotoPrefetchIndex(",
             "//  подсказка фоновому предзагрузчику")),
    ("GalleryService.cpp: the percent shown in the status line",
     extract(gallery, "static double PhotoScalePercent(",
             "// Строка информации")),
    ("GalleryService.h: what a gallery key means (paged vs picker)",
     extract(gallery_h, "enum class GalleryKeyAction",
             "// Фотогалерея поверх фото-сессии")),
    ("GalleryService.cpp: the key map itself",
     extract(gallery, "static GalleryKeyAction DecideGalleryKey(",
             "LRESULT CALLBACK GalleryService::_KeyboardHookProc(")),
    ("GalleryService.cpp: the Num6 upscaler cycle",
     extract(gallery, "static int NextUpscalerCycle(",
             "void GalleryService::_CycleUpscaler(")),
    ("GalleryService.cpp: wheel notches to page steps",
     extract(gallery, "static int WheelPageSteps(",
             "void GalleryService::_OnMouseWheel(")),
    ("ScalingService.cpp: which part of the cursor's monitor the stage takes",
     extract(repo / "src/GMagpie/ScalingService.cpp", "static RECT PhotoStageRect(",
             "void ScalingService::_PlacePhotoStageAtCursor(")),
    ("App.cpp: the --gallery lite-mode argument scan",
     extract(app, "static bool HasGalleryArgument(",
             "// Фотогалерея из командной строки")),
    ("GalleryService.cpp: EXIF orientations that swap the displayed size",
     extract(gallery, "static bool PhotoAppliesExifRotation(",
             "namespace gallery_status {")),
]

out.joinpath("PhotoGalleryUnderTest.h").write_text(
    "// Generated by prepare_photo_gallery_test.py - production code, do not edit.\n"
    "#pragma once\n\n"
    + "\n".join(f"// --- {title} ---\n{code}" for title, code in parts)
    + "\n", encoding="utf-8")
print(f"Extracted {len(parts)} photo-gallery functions for CPU tests.")
